// yms-home build: the same maven deploy YonCode's deployYmsHome runs, plus the
// config pull/adapt and JDK pointer. From scratch on a fresh machine this
// needs only: JDK, maven, network to jfrog (anonymous read) — no local assets.

import { spawn } from 'node:child_process'
import { existsSync, mkdirSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { artifactoryUrl } from './config.js'

export function ymsHomeIsBuilt(cfg) {
  return existsSync(join(cfg.ymsHome, 'yms.jar')) && existsSync(join(cfg.ymsHome, 'middleware', 'lib'))
}

/** Locate the bootstrap module dir (the one whose mvn build deploys the war). */
export function findBootstrapDir(cfg) {
  if (cfg.projectDir == null) throw new Error('未找到项目目录')
  const direct = join(cfg.projectDir, 'c-ass-kk-hans-be', 'dev-c-ass-kk-hans-bootstrap')
  if (existsSync(direct)) return direct
  // generic: scan every child dir of the project for a *bootstrap module
  // with a pom.xml (covers <module>-be/dev-<module>-bootstrap and any layout)
  for (const name of readdirSync(cfg.projectDir)) {
    const be = join(cfg.projectDir, name)
    try {
      if (!statSync(be).isDirectory() || name.startsWith('.') || name === 'node_modules') continue
    } catch { continue }
    for (const sub of readdirSync(be)) {
      if (/bootstrap/.test(sub) && existsSync(join(be, sub, 'pom.xml'))) return join(be, sub)
    }
  }
  throw new Error('未找到 bootstrap 模块目录（*bootstrap/pom.xml）')
}

/**
 * Generate a maven settings.xml with the jfrog repo derived from the
 * workbench URL (anonymous read works) — used when the machine has no
 * settings of its own or ~/.m2 has a hijacking mirror.
 */
/** XML-escape a value interpolated into the generated settings.xml. */
function xmlEsc(v) {
  return String(v).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;').replace(/'/g, '&apos;')
}

export function ensureMavenSettings(cfg) {
  if (cfg.maven.settingsXml !== null && existsSync(cfg.maven.settingsXml)) return cfg.maven.settingsXml
  const path = join(cfg.stateDir, 'maven-settings.xml')
  mkdirSync(cfg.stateDir, { recursive: true })
  const repo = artifactoryUrl(cfg)
  const localRepo = cfg.maven.repo !== null ? `\n    <localRepository>${xmlEsc(resolve(cfg.maven.repo))}</localRepository>` : ''
  const xml = `<?xml version="1.0" encoding="UTF-8"?>
<settings xmlns="http://maven.apache.org/SETTINGS/1.0.0">
  <!-- generated by dsh-ris-yds: jfog repo = workbench host artifactory -->
${localRepo}
  <profiles>
    <profile>
      <id>yds</id>
      <repositories>
        <repository>
          <id>jfrog</id>
          <url>${xmlEsc(repo)}</url>
          <releases><enabled>true</enabled><checksumPolicy>ignore</checksumPolicy></releases>
          <snapshots><enabled>true</enabled><checksumPolicy>ignore</checksumPolicy></snapshots>
        </repository>
      </repositories>
      <pluginRepositories>
        <pluginRepository>
          <id>jfrog</id>
          <url>${xmlEsc(repo)}</url>
          <releases><enabled>true</enabled><checksumPolicy>ignore</checksumPolicy></releases>
          <snapshots><enabled>true</enabled><checksumPolicy>ignore</checksumPolicy></snapshots>
        </pluginRepository>
      </pluginRepositories>
    </profile>
  </profiles>
  <activeProfiles><activeProfile>yds</activeProfile></activeProfiles>
</settings>
`
  writeFileSync(path, xml, 'utf8')
  return path
}

/** Run the yms-module maven deploy into cfg.ymsHome. Long (first run: kernel 77MB download). */
export function buildYmsHome(cfg, { onStdout, signal } = {}) {
  const bootstrap = findBootstrapDir(cfg)
  const settingsXml = ensureMavenSettings(cfg)
  // libProjectsFile: /dev/null is a POSIX-only trick — use the real marker
  // file (ensureHomeMarkers writes it) so Windows maven gets a valid path.
  const libProjectsFile = join(cfg.ymsHome, '.libraryProjects.list')
  const args = [
    '-B', '-ntp', '-s', settingsXml,
    'com.yonyou.iuap:yms-module-simplify-maven-plugin:1.0.2-RELEASE:dev',
    '-Dyms.dev.skipRun=true',
    `-Dyms.workDirectory=${cfg.ymsHome}`,
    `-Dyms.dev.libProjectsFile=${libProjectsFile}`,
    '-Dmaven.test.skip=true',
  ]
  return new Promise((resolve_, reject_) => {
    // Windows: mvn is mvn.cmd and .cmd needs a cmd.exe host (Node ≥18.20
    // refuses .cmd without shell). POSIX: keep plain spawn.
    const useShell = process.platform === 'win32'
    const child = spawn(useShell ? 'mvn.cmd' : 'mvn', args, { cwd: bootstrap, signal, shell: useShell, windowsHide: true })
    // output is streamed to onStdout only — never buffered (a 19-minute
    // first build must not accumulate the whole log in memory).
    const onData = (chunk) => {
      if (onStdout !== undefined) onStdout(chunk.toString())
    }
    child.stdout.on('data', onData)
    child.stderr.on('data', onData)
    child.once('error', reject_)
    child.once('close', (code) => {
      if (code === 0) resolve_({ ok: true, bootstrap, settingsXml })
      else reject_(new Error(`mvn 退出码 ${code}（输出尾部见日志）`))
    })
  })
}
